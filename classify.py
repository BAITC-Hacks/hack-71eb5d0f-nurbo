#!/usr/bin/env python3
"""Классификатор обращений: категория (справка / жалоба / другое) + черновик ответа.

Без внешних зависимостей. Запуск: python3 classify.py [путь_к_файлу]
"""
import re
import sys
from pathlib import Path

# Правила: (категория, список корней-ключевых слов). Порядок важен — первое совпадение выигрывает.
RULES = [
    ("справка", ["справк"]),
    ("жалоба", ["очередь", "холодн", "пропал", "не работает", "сломан",
                "грязн", "шум", "жалоб", "плохо", "нет воды", "нет света"]),
]

# Черновики ответов (на русском) по категориям.
REPLIES = {
    "справка": (
        "Здравствуйте! Справку о месте учёбы можно заказать в офисе регистратора "
        "или через личный кабинет. Срок выдачи — обычно 1–3 рабочих дня. "
        "Если нужна справка в конкретный орган, укажите это в заявке."
    ),
    "жалоба": (
        "Здравствуйте! Благодарим за обращение и приносим извинения за неудобства. "
        "Мы передали информацию ответственному подразделению и вернёмся к вам "
        "с ответом в ближайшее время."
    ),
    "другое": (
        "Здравствуйте! Спасибо за обращение. Мы передали ваш вопрос "
        "ответственному сотруднику — он свяжется с вами и уточнит детали."
    ),
}


def classify(text: str) -> str:
    t = text.lower()
    for category, keywords in RULES:
        if any(k in t for k in keywords):
            return category
    return "другое"


def load_messages(path: Path) -> list[str]:
    """Читает файл, убирает нумерацию вида '1) ' в начале строки."""
    lines = path.read_text(encoding="utf-8").splitlines()
    return [re.sub(r"^\s*\d+\)\s*", "", ln).strip() for ln in lines if ln.strip()]


def main() -> None:
    path = Path(sys.argv[1] if len(sys.argv) > 1 else "messages.txt")
    for i, msg in enumerate(load_messages(path), start=1):
        cat = classify(msg)
        print(f"{i}) {msg}")
        print(f"   Категория: {cat}")
        print(f"   Ответ: {REPLIES[cat]}")
        print()


if __name__ == "__main__":
    main()
